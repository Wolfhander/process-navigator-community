import fs from 'node:fs';
import path from 'node:path';
import assert from 'node:assert/strict';
import {analyticsCsv,defaultAnalyticsSelection,analyticsPresetKey,readAnalyticsPresets,writeAnalyticsPresets} from '../frontend/process-navigator-ui/src/analytics-workspace.ts';
const folder=process.argv[2];
const data=JSON.parse(fs.readFileSync(path.join(folder,'analytics-actual.json'),'utf8'));
const current={...defaultAnalyticsSelection,query:'md-order',view:'processes',metrics:['readiness','coverage']};
const memory=new Map(),storage={getItem:k=>memory.get(k)??null,setItem:(k,v)=>memory.set(k,v)};
assert.equal(writeAnalyticsPresets(storage,analyticsPresetKey('master-analyst'),[{id:'master-view',name:'Заказ MD-001',selection:current}]),'');
assert.deepEqual(readAnalyticsPresets(storage,analyticsPresetKey('master-analyst')).presets[0].selection,current);
assert.equal(readAnalyticsPresets(storage,analyticsPresetKey('other-profile')).presets.length,0);
console.log('[master-data:analytics-views] PASS');
const loadedAt=new Date().toISOString();
const selected=analyticsCsv(data,current,'processes',loadedAt),portfolio=analyticsCsv(data,current,'portfolio',loadedAt);
assert.ok(selected.includes('"md-order"'));assert.ok(!selected.includes('"md-design"'));
assert.ok(portfolio.includes('"md-design"'));assert.ok(portfolio.includes('"readiness";"Готовность описания";"100"'));
assert.ok(portfolio.includes('"source_totalDepartments"'));assert.ok(portfolio.includes('"source_participatingDepartments"'));
fs.writeFileSync(path.join(folder,'analytics-selected.csv'),selected);
fs.writeFileSync(path.join(folder,'analytics-portfolio.csv'),portfolio);
fs.writeFileSync(path.join(folder,'analytics-view.json'),JSON.stringify({schemaVersion:1,presets:readAnalyticsPresets(storage,analyticsPresetKey('master-analyst')).presets},null,2));
console.log('[master-data:analytics-export] PASS');
