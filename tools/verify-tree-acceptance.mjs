import assert from 'node:assert/strict';
import fs from 'node:fs';
import {decompositionTree,visibleDecompositionRows,decompositionPage} from '../frontend/process-navigator-ui/src/decomposition-tree.ts';
const spec=JSON.parse(fs.readFileSync(new URL('../master-data/tree-cases.json',import.meta.url),'utf8'));
assert.equal(process.argv[2],'http://127.0.0.1:5087','Use the isolated acceptance server only.');
const response=await fetch(process.argv[2]+'/api/processes/decomposition',{headers:{'X-Process-Navigator-User':'demo-superadministrator'}});
assert.equal(response.status,200);
const data=await response.json();
assert.equal(data.links.filter(l=>l.sourceProcessId===spec.rootId).length,spec.callCount);
const tree=decompositionTree(data);
assert.equal(tree.rows.length,spec.expectedRowLimit);assert.equal(tree.rowLimitReached,true);
assert.equal(tree.depthLimitReached,true);assert.ok(tree.rows.some(r=>r.processId==='tree-deep-20'&&r.depthLimited));
assert.equal(tree.rows.filter(r=>r.processId.startsWith('tree-deep-')&&r.depth===0).length,1);
assert.equal(new Set(tree.rows.map(row=>row.key)).size,tree.rows.length);
const pages=Array.from({length:20},(_,i)=>decompositionPage(tree.rows,i,spec.pageSize).rows);
assert.deepEqual(pages.flat().map(r=>r.key),tree.rows.map(r=>r.key));
assert.ok(visibleDecompositionRows(tree.rows,new Set(),spec.searchIncluded).length>0);
assert.equal(visibleDecompositionRows(tree.rows,new Set(),spec.searchExcluded).length,0);
fs.writeFileSync(new URL('../artifacts/tree-acceptance-20261030/tree-actual.json',import.meta.url),JSON.stringify(data));
console.log('Tree API acceptance passed: 3000 real call links, 30-model depth chain, 2000 bounded occurrences, 20 pages, independent keys and explicit search limits.');
